#!/usr/bin/env python3
"""Single source of truth for the visual design: design/tokens.json -> Kotlin, Swift and docs.
Run from the repo root:  python3 tools/design/gen_tokens.py
"""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
t = json.loads((root / "design/tokens.json").read_text())

def camel(*parts):
    s = "".join(p[:1].upper() + p[1:] for p in parts)
    return s[:1].lower() + s[1:]

colors = {camel(k): v for k, v in t["colors"].items()}
for st, d in t["status"].items():
    colors[camel("bar", st)] = d["bar"]; colors[camel("pill", st, "bg")] = d["pillBg"]; colors[camel("pill", st, "fg")] = d["pillFg"]
dims = {}
for grp in ("radius", "space", "size", "font"):
    for k, v in t[grp].items(): dims[camel(grp, k)] = v

def kt_color(h): return f"Color(0xFF{h[1:].upper()})"
kt = ["// GENERATED by tools/design/gen_tokens.py from design/tokens.json — do not edit.",
      "package uz.lokmago.restaurant.ui.theme", "", "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "import androidx.compose.ui.unit.sp", "",
      "object Dt {"]
kt += [f"    val {k} = {kt_color(v)}" for k, v in colors.items()]
for k, v in dims.items():
    unit = "sp" if k.startswith("font") else "dp"
    kt.append(f"    val {k} = {v}.{unit}")
kt.append("}")
(root / "app/src/main/java/uz/lokmago/restaurant/ui/theme/DesignTokens.kt").write_text("\n".join(kt) + "\n")

sw = ["// GENERATED by tools/design/gen_tokens.py from design/tokens.json — do not edit.", "import SwiftUI", "",
      "extension Color {", "    init(hex: UInt32) {",
      "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255, opacity: 1)",
      "    }", "}", "", "enum Dt {"]
sw += [f"    static let {k} = Color(hex: 0x{v[1:].upper()})" for k, v in colors.items()]
sw += [f"    static let {k}: CGFloat = {v}" for k, v in dims.items()]
sw.append("}")
(root / "ios/LokmaRestaurant/DesignTokens.swift").write_text("\n".join(sw) + "\n")

md = ["# Dizayn tokenlari (Android = iOS)", "", "Manba: `design/tokens.json` (mockup'dan o'lchangan). Generator: `python3 tools/design/gen_tokens.py` → `DesignTokens.kt` va `DesignTokens.swift`.", "",
      "| Token | Qiymat |", "|---|---|"]
md += [f"| `{k}` | `{v}` |" for k, v in colors.items()] + [f"| `{k}` | `{v}` |" for k, v in dims.items()]
md += ["", "## Holat ranglari", "", "| Holat | Chap chiziq | Pill foni | Pill matni |", "|---|---|---|---|"]
md += [f"| {s} | `{d['bar']}` | `{d['pillBg']}` | `{d['pillFg']}` |" for s, d in t["status"].items()]
(root / "design/DESIGN.md").write_text("\n".join(md) + "\n")
print(f"{len(colors)} colours, {len(dims)} dimensions -> Kotlin, Swift, DESIGN.md")
